import assert from 'node:assert/strict';
import {buildWordCloud} from '../src/wordCloudLogic.ts';
const rows=[{id:'a',status:'done',result:{transcript:'克制 克制 AI',level:'transcribed'}},{id:'b',status:'done',result:{transcript:'檢查產出',level:'transcribed'}},{id:'c',status:'failed'}];
assert.equal(buildWordCloud(rows,null).words.length,0);
assert.equal(buildWordCloud(rows,{themes:[{title:'舊摘要',response_ids:['a']}]}).words.length,0);
const result={concept_version:1,response_ids:['a','b'],themes:[{title:'核對 AI 生成內容',response_ids:['a','a','b','c','invented'],count:999}]};
const cloud=buildWordCloud(rows,result);
assert.deepEqual(cloud.words,[{text:'核對 AI 生成內容',count:2,responseIds:['a','b']}]);
assert.equal(cloud.responses,2);
assert(!cloud.words.some(w=>w.text==='克制'));
console.log('PASS: requires semantic summary, no raw-token fallback, validates and deduplicates evidence, computes counts.');
